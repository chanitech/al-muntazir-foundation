<?php

namespace App\Exports;

use Maatwebsite\Excel\Concerns\FromArray;
use Maatwebsite\Excel\Concerns\WithTitle;
use Maatwebsite\Excel\Concerns\WithStyles;
use Maatwebsite\Excel\Concerns\WithDrawings;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;
use PhpOffice\PhpSpreadsheet\Worksheet\Drawing;
use PhpOffice\PhpSpreadsheet\Style\Fill;
use PhpOffice\PhpSpreadsheet\Style\Color;
use PhpOffice\PhpSpreadsheet\Style\Alignment;
use PhpOffice\PhpSpreadsheet\Style\Border;
use App\Models\Member;
use Maatwebsite\Excel\Concerns\WithMultipleSheets;
use Maatwebsite\Excel\Concerns\WithProperties;
use Maatwebsite\Excel\Concerns\WithHeadings;        


class CoverSheet implements FromArray, WithTitle, WithStyles, WithDrawings
{
    protected $filters;

    public function __construct(array $filters = [])
    {
        $this->filters = $filters;
    }

   public function array(): array
{
    return [
        ['AL MUNTAZIR MEMBERS REPORT'],
        [],
        ['Generated on:', now()->format('F j, Y H:i:s')],
        ['Generated by:', auth()->user()->name ?? 'System'],
        [],
        ['FILTERS APPLIED'],
        [$this->getFilterText()],
        [],
        ['Report includes all members matching the above filters.'],
        ['For detailed data, see "Members Data" sheet.'],
        ['Summary statistics are in "Summary" sheet.'],
    ];
}

private function getFilterText(): string
{
    if (empty($this->filters)) {
        return 'No filters applied (all members)';
    }
    $parts = [];
    foreach ($this->filters as $key => $value) {
        if (!empty($value)) {
            $parts[] = ucfirst(str_replace('_', ' ', $key)) . ': ' . $value;
        }
    }
    return implode('; ', $parts);
}

    public function title(): string
    {
        return 'Cover';
    }

    public function drawings()
    {
        $drawing = new Drawing();
        $drawing->setName('Logo');
        $drawing->setDescription('Organization Logo');
        $drawing->setPath(public_path('images/logo.png')); // Ensure this file exists
        $drawing->setHeight(80);
        $drawing->setCoordinates('A1');

        return $drawing;
    }

    public function styles(Worksheet $sheet)
    {
        // Auto-size columns
        foreach (range('A', 'B') as $col) {
            $sheet->getColumnDimension($col)->setAutoSize(true);
        }

        // Style the main title
        $sheet->mergeCells('A3:B3');
        $sheet->setCellValue('A3', 'AL MUNTAZIR MEMBERS REPORT');
        $sheet->getStyle('A3')->applyFromArray([
            'font' => [
                'bold' => true,
                'size' => 18,
                'color' => ['argb' => 'FFFFFF'],
            ],
            'fill' => [
                'fillType' => Fill::FILL_SOLID,
                'startColor' => ['argb' => 'FF1F4E79'],
            ],
            'alignment' => [
                'horizontal' => Alignment::HORIZONTAL_CENTER,
                'vertical' => Alignment::VERTICAL_CENTER,
            ],
        ]);
        $sheet->getRowDimension(3)->setRowHeight(30);

        // Style the generated info
        $sheet->getStyle('A5:B6')->applyFromArray([
            'font' => ['size' => 11],
            'borders' => [
                'outline' => [
                    'borderStyle' => Border::BORDER_THIN,
                ],
            ],
        ]);

        // Style filters header
        $sheet->getStyle('A8')->applyFromArray([
            'font' => ['bold' => true, 'size' => 12],
            'fill' => [
                'fillType' => Fill::FILL_SOLID,
                'startColor' => ['argb' => 'FFD9E1F2'],
            ],
        ]);

        // Style filter value
        $sheet->getStyle('A9')->applyFromArray([
            'font' => ['italic' => true],
        ]);

        // Footer note
        $sheet->getStyle('A11:A13')->applyFromArray([
            'font' => ['size' => 10, 'color' => ['argb' => 'FF555555']],
        ]);
    }
}